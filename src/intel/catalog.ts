export function lookup(catalog: Catalog, name: string): Tech | undefined {
  const direct = catalog[name] ?? catalog[name.toLowerCase()];
  if (direct) return direct;
  for (const [k, v] of Object.entries(catalog)) {
    if (k.endsWith('*') && name.toLowerCase().startsWith(k.slice(0, -1).toLowerCase())) return v;
  }
  return undefined;
}

