/**
 * Dependency → technology catalogue used by project intelligence. Keys are package names per ecosystem; a key
 * ending in `*` matches by prefix.
 */
export type TechKind =
  | 'frontend'
  | 'backend'
  | 'fullstack'
  | 'mobile'
  | 'desktop'
  | 'orm'
  | 'database'
  | 'queue'
  | 'cache'
  | 'auth'
  | 'observability'
  | 'testing'
  | 'lint'
  | 'build'
  | 'payments'
  | 'integration'
  | 'http-client'
  | 'validation';

export interface Tech {
  name: string;
  kind: TechKind;
}

type Catalog = Record<string, Tech>;

const t = (name: string, kind: TechKind): Tech => ({ name, kind });

