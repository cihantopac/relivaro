function mainHelp(): string {
  const lines = [
    `Relivaro ${VERSION} — Verify the code. Prove the quality. Ship with confidence.`,
    '',
    'Usage: relivaro <command> [path] [options]',
    '',
    'Commands:',
    ...COMMANDS.filter((c) => !c.spec.hidden).map((c) => `  ${c.spec.name.padEnd(12)} ${c.spec.summary}`),
    '  version      Print the version',
    '',
    'Safety: read-only by default. Project code runs only with --allow-exec, the network is used only with',
    '--online (OSV.dev) or `load`, and files change only through `fix apply --yes` (with backup and rollback).',
    '',
    'Run `relivaro <command> --help` for details. Docs: https://github.com/cihantopac/relivaro',
  ];
  return lines.join('\n');
}

/** CLI reference generated from the command registry (docs/CLI.md and the plugin's reference file). */
export function cliMarkdown(): string {
  const L = [
    '# Relivaro CLI reference',
    '',
    '<!-- Generated by `npm run build` from src/cli/commands.ts. Do not edit by hand. -->',
    '',
    `Version ${VERSION}. All commands accept \`--json\` (machine-readable output on stdout, errors as JSON on stderr), \`--quiet\`, \`--no-color\` and \`--help\`.`,
    '',
    '## Exit codes',
    '',
    '| Code | Meaning |',
    '| --- | --- |',
    '| 0 | Success (no gate failed) |',
    '| 1 | A gate failed: findings at/above `--fail-on`, release not ready, breaking API change, fix verification failed, rollback conflict |',
    '| 2 | Usage or configuration error, missing permission flag (`--allow-exec`, `--yes`), refused target |',
    '| 3 | Unexpected runtime error |',
    '| 4 | Partial run: a limit (`--max-duration`, `--max-files`, `--max-bytes`) or SIGTERM/SIGINT stopped it early; the record is written with `partial` |',
    '',
  ];
  for (const c of COMMANDS) {
    const s = c.spec;
    L.push(`## \`relivaro ${s.name}\``, '', `${s.summary}.`, '', '```', s.usage, '```', '');
    if (s.description)
      L.push(s.description.includes('\n') ? `\`\`\`\n${s.description}\n\`\`\`` : s.description, '');
    if (s.options.length) {
      L.push('| Option | Description |', '| --- | --- |');
      for (const o of s.options)
        L.push(
          `| \`--${o.name}${o.type === 'boolean' ? '' : ` ${o.value ?? `<${o.type}>`}`}\` | ${o.description.replace(/\|/g, '\\|')}${o.default !== undefined && o.type !== 'boolean' ? ` Default: \`${o.default}\`.` : ''} |`,
        );
      L.push('');
    }
    if (s.examples?.length) L.push('Examples:', '', '```bash', ...s.examples, '```', '');
  }
  L.push('## Global options', '', '| Option | Description |', '| --- | --- |');
  for (const o of GLOBAL_OPTIONS) L.push(`| \`--${o.name}\` | ${o.description} |`);
  return `${L.join('\n')}\n`;
}

export function rulesMarkdown(): string {
  const rules = allRuleMeta();
  const L = [
    '# Relivaro rule reference',
    '',
    '<!-- Generated by `npm run build` from the rule registry. Do not edit by hand. -->',
    '',
    `${rules.length} rules. Severity and confidence are defaults; findings may adjust them (e.g. user input confirmed → higher confidence, test files → lower). Configure with \`rules\` in \`relivaro.config.json\`.`,
    '',
  ];
  L.push(
    '| Rule | Category | Severity | Confidence | Standards | Fixer |',
    '| --- | --- | --- | --- | --- | --- |',
  );
  for (const r of rules)
    L.push(
      `| [\`${r.id}\`](#${r.id.replace(/[^a-z0-9]+/g, '-')}) | ${r.category} | ${r.severity} | ${r.confidence} | ${[...(r.cwe ?? []), ...(r.owasp ?? [])].join(', ')} | ${r.fixer ? `\`${r.fixer}\`` : ''} |`,
    );
  L.push('');
  for (const r of rules) {
    L.push(
      `## ${r.id}`,
      '',
      `**${r.title}** — ${r.category}, default severity ${r.severity}, confidence ${r.confidence}.`,
      '',
      r.description,
      '',
      `- **Impact:** ${r.impact}`,
      `- **Fix:** ${r.recommendation}`,
      `- **Verify:** ${r.verification}`,
    );
    if (r.references?.length) L.push(`- **References:** ${r.references.join(', ')}`);
    L.push('');
  }
  L.push('## Automated fixers', '', '| Fixer | Safety | Change | Notes |', '| --- | --- | --- | --- |');
  for (const f of FIXERS) L.push(`| \`${f.id}\` | ${f.safety} | ${f.title} | ${f.description} |`);
  L.push(
    '',
    '`safe` fixers preserve behaviour for correct programs; `review` fixers intentionally change behaviour (e.g. enabling TLS verification) and should be reviewed before applying.',
  );
  return `${L.join('\n')}\n`;
}

export async function main(argv: string[]): Promise<number> {
  const [cmdName, ...rest] = argv;
  const jsonMode = argv.includes('--json');
  try {
    if (!cmdName || cmdName === '--help' || cmdName === '-h' || cmdName === 'help') {
      const target = cmdName === 'help' ? COMMANDS.find((c) => c.spec.name === rest[0]) : undefined;
      process.stdout.write(`${target ? helpText(target.spec) : mainHelp()}\n`);
      return EXIT.OK;
    }
    if (cmdName === 'version' || cmdName === '--version' || cmdName === '-v') {
      process.stdout.write(jsonMode ? `${JSON.stringify({ version: VERSION })}\n` : `${VERSION}\n`);
      return EXIT.OK;
    }
    if (cmdName === '__cli-markdown') {
      process.stdout.write(cliMarkdown());
      return EXIT.OK;
    }
    if (cmdName === '__rules-markdown') {
      process.stdout.write(rulesMarkdown());
      return EXIT.OK;
    }
    const cmd = COMMANDS.find((c) => c.spec.name === cmdName);
    if (!cmd)
      throw new RelivaroError(
        'USAGE',
        `Unknown command "${cmdName}".`,
        'Run `relivaro --help` for the list of commands.',
      );
    const parsed = parseArgs(rest, cmd.spec);
    if (parsed.opts.help) {
      process.stdout.write(`${helpText(cmd.spec)}\n`);
      return EXIT.OK;
    }
    applyExecutionPolicy(cmd.spec.name, parsed);
    const out = makeOut({
      json: !!parsed.opts.json,
      quiet: !!parsed.opts.quiet,
      color: parsed.opts['no-color'] ? false : undefined,
      progress: parsed.opts.progress as ProgressMode | undefined,
    });
    return await cmd.run(parsed, out);
  } catch (e) {
    clearProgress();
    const err = e instanceof RelivaroError ? e : new RelivaroError('INTERNAL', errorMessage(e));
    const message = redact(err.message);
    if (jsonMode)
      process.stderr.write(`${JSON.stringify({ error: { code: err.code, message, hint: err.hint } })}\n`);
    else {
      process.stderr.write(`relivaro: ${message}\n`);
      if (err.hint) process.stderr.write(`hint: ${redact(err.hint)}\n`);
      if (err.code === 'INTERNAL' && process.env.RELIVARO_DEBUG && e instanceof Error)
        process.stderr.write(`${e.stack}\n`);
    }
    return err.exitCode;
  }
}

// Entry point (the bundle is executed directly).
const isEntry = process.argv[1] && /relivaro(?:\.mjs)?$|main\.[cm]?[jt]s$/.test(process.argv[1]);
if (isEntry) {
  // The first SIGTERM/SIGINT stops the analysis gracefully: the run is written as partial (exit code 4). A second
  // signal exits immediately with the conventional 128 + signal number.
  for (const [sig, code] of [
    ['SIGTERM', 143],
    ['SIGINT', 130],
  ] as const)
    process.on(sig, () => {
      if (processAbort.signal.aborted) process.exit(code);
      processAbort.abort();
    });
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (e) => {
      process.stderr.write(`relivaro: ${errorMessage(e)}\n`);
      process.exitCode = EXIT.RUNTIME;
    },
  );
}
