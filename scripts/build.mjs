#!/usr/bin/env node
// Bundles the Relivaro CLI into plugin/dist/relivaro.mjs with its tree-sitter grammars. dist/ is committed so the
// Claude Code plugin works right after install, with no npm install and no native compilation.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outdir = process.argv[2] ? resolve(process.cwd(), process.argv[2]) : join(root, 'plugin', 'dist');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const require = createRequire(join(root, 'package.json'));
const { existsSync } = await import('node:fs');
/** Package directory even when `package.json` is not in the package's exports map. */
function pkgDir(name) {
  try {
    return dirname(require.resolve(`${name}/package.json`));
  } catch {
    let d = dirname(require.resolve(name));
    while (!existsSync(join(d, 'package.json'))) d = dirname(d);
    return d;
  }
}

rmSync(outdir, { recursive: true, force: true });
mkdirSync(join(outdir, 'grammars'), { recursive: true });

await build({
  entryPoints: [join(root, 'src/cli/main.ts')],
  outfile: join(outdir, 'relivaro.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  minify: false,
  keepNames: false,
  legalComments: 'eof',
  sourcemap: false,
  logLevel: 'warning',
  define: { __RELIVARO_VERSION__: JSON.stringify(pkg.version) },
  banner: {
    js: [
      '#!/usr/bin/env node',
      `// Relivaro ${pkg.version} - generated by scripts/build.mjs. Do not edit; edit src/ instead.`,
      "import { createRequire as __relivaroCreateRequire } from 'node:module';",
      'const require = __relivaroCreateRequire(import.meta.url);',
    ].join('\n'),
  },
});

// WASM runtime and grammars (MIT licensed; licenses copied next to them).
const assets = [
  ['web-tree-sitter', 'web-tree-sitter.wasm'],
  ['tree-sitter-javascript', 'tree-sitter-javascript.wasm'],
  ['tree-sitter-typescript', 'tree-sitter-typescript.wasm'],
  ['tree-sitter-typescript', 'tree-sitter-tsx.wasm'],
  ['tree-sitter-php', 'tree-sitter-php.wasm'],
  ['tree-sitter-python', 'tree-sitter-python.wasm'],
];
const licenses = [];
for (const [pkgName, file] of assets) {
  const dir = pkgDir(pkgName);
  copyFileSync(join(dir, file), join(outdir, 'grammars', file));
  if (!licenses.includes(pkgName)) {
    licenses.push(pkgName);
    const p = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    let text = '';
    try {
      text = readFileSync(join(dir, 'LICENSE'), 'utf8');
    } catch {
      text = `${p.name}@${p.version} — license: ${p.license}`;
    }
    writeFileSync(join(outdir, 'grammars', `${pkgName}.LICENSE.txt`), `${p.name}@${p.version}\n\n${text}`);
  }
}
console.log(`built ${join(outdir, 'relivaro.mjs')}`);

// Generated docs: CLI and rule reference come from the registries so docs never drift from code.
if (!process.argv[2]) {
  const { execFileSync } = await import('node:child_process');
  const run = (arg) => execFileSync(process.execPath, [join(outdir, 'relivaro.mjs'), arg], { encoding: 'utf8' });
  const cli = run('__cli-markdown');
  const rules = run('__rules-markdown');
  mkdirSync(join(root, 'docs'), { recursive: true });
  writeFileSync(join(root, 'docs', 'CLI.md'), cli);
  writeFileSync(join(root, 'docs', 'RULES.md'), rules);
  mkdirSync(join(root, 'plugin', 'skills', 'relivaro', 'references'), { recursive: true });
  writeFileSync(join(root, 'plugin', 'skills', 'relivaro', 'references', 'cli.md'), cli);
  writeFileSync(join(root, 'plugin', 'skills', 'relivaro', 'references', 'rules.md'), rules);
}
